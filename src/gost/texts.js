const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';

/**
 * Уникальное буквенное обозначение по порядковому номеру: A…Z, AA, AB…
 * (биективная система счисления). Нужна, потому что части «Границы цикла» должны иметь
 * один и тот же идентификатор (п. 3.2.2.6), а парные соединители — одно и то же
 * уникальное обозначение (п. 3.4.1): повторяться в пределах схемы они не могут.
 * @param {number} index номер с нуля
 */
export function letterId(index) {
  if (!Number.isInteger(index) || index < 0) throw new RangeError('Номер обозначения должен быть целым неотрицательным');
  let n = index + 1;
  let out = '';
  while (n > 0) {
    const r = (n - 1) % ALPHABET.length;
    out = ALPHABET[r] + out;
    n = (n - 1 - r) / ALPHABET.length;
  }
  return out;
}
